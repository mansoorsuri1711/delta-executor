export function formatValue(n: number): string {
  if (!Number.isFinite(n) || n <= 0) return "0";
  if (n >= 1_000_000_000) {
    const v = n / 1_000_000_000;
    return `${Number(v.toFixed(v >= 10 ? 1 : 2))}B`;
  }
  if (n >= 1_000_000) {
    const v = n / 1_000_000;
    return `${Number(v.toFixed(v >= 10 ? 1 : 2))}M`;
  }
  if (n >= 1_000) {
    const v = n / 1_000;
    return `${Number(v.toFixed(v >= 10 ? 1 : 2))}K`;
  }
  return String(Math.round(n));
}

export function getFruitById(id: string): BloxFruit | undefined {
  return BLOX_FRUITS.find((f) => f.id === id);
}

export type ValueMode = 'physical' | 'permanent';

export function fruitValue(fruit: BloxFruit, mode: ValueMode): number {
  return mode === 'permanent' ? fruit.permanentValue : fruit.physicalValue;
}
